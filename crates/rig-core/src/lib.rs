/// Поколение ядра — слот «ядро» в паспорте версии (`docs/VERSIONS.md`).
///
/// Считается хронологически: это номер правки контракта ядра, начиная с 1.
/// Контракт — это то, что видит скрипт или файл пресета: функции DSL,
/// параметры кадра, виды объектов, семантика кадра. Правки без изменения
/// контракта (сборка, диагностика, исправления) номер не двигают.
///
/// Полная таблица с коммитами — `docs/VERSIONS.md`, раздел «Хронология ядра».
/// Сверить, что ни одна правка не забыта, помогает `npm run version:report`.
///
/// Растёт, когда прежнее ядро новую формулу уже не поймёт: оно молча вернёт
/// ноль. Редактор спрашивает это число запросом `{ "op": "version" }` и
/// сравнивает со своим — так видно, что сборку пора пересобрать.
pub const CORE_GENERATION: u32 = 21;

/// Старейшее поколение сценариев, которое это ядро ещё понимает без потерь.
///
/// Поколения не обязаны совпадать: сцене из одних спрайтов достаточно ядра 4,
/// и она спокойно работает на 21. Совместимость ломается только тогда, когда
/// из языка **убрали**, переименовали или изменили смысл старого поведения, —
/// вот тогда это число растёт до поколения, в котором правка произошла.
///
/// Добавили новую функцию или вид объекта — число не двигается: старое
/// поведение осталось на месте. Поэтому новая сборка ядра не ломает старые
/// сцены, а сцена, написанная под новое, честно просит своё поколение (поле
/// `needs` в пресете).
///
/// Сейчас это 16: в шестнадцатом поколении из языка убрали `hold`/`relax` и
/// `trigger имя = …`, вместо них появились `in` и `event`. Сценарии, писавшиеся
/// под ядра 1…15 и пользующиеся убранным, на этом ядре уже не разберутся —
/// редактор покажет это отдельной плашкой (таблица `src/engine/coreFeatures.ts`).
///
/// Отдаётся вместе с `CORE_GENERATION` в ответе на `{ "op": "version" }`:
/// редактор сверяет и умение ядра, и его совместимость со сценой.
pub const ACCEPTS_FROM: u32 = 16;

