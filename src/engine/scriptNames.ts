/**
 * Имена, которые скрипт объекта понимает без объявления.
 *
 * Один список на редактор и на разбор требований к ядру: подсказки показывают
 * эти имена, а признак «локальная переменная» узнаёт себя ровно по обратному —
 * имя слева не входит в список, значит автор завёл свою переменную (ядро 25).
 * Разъехавшись, два места дали бы разное поведение одного и того же скрипта:
 * редактор подсказывал бы одно, а ядро считало другое.
 *
 * Источник истины — `Param::parse` и `Param::channel_of` в
 * `crates/rig-core/src/model.rs`.
 */

/** Числовые параметры объекта вместе с каналами поведения. */
export const SCRIPT_PARAMETERS: readonly string[] = [
  "x", "y", "rotation", "sizeX", "sizeY", "skewX", "skewY", "opacity", "visible", "layer",
  // Каналы поведения: блок вкладки «Поведение» пишет только их, а параметр
  // складывает добавку с авторским кодом (см. `behaviourBlock`).
  "x_behaviour", "y_behaviour", "rotation_behaviour", "sizeX_behaviour", "sizeY_behaviour",
  "opacity_behaviour", "visible_behaviour",
  // Маска: 1 — режет по контуру, 0 — объект целиком (см. «Маска» в инспекторе).
  "mask",
  // Деформация: углы в процентах размера зоны (см. «Деформация» в инспекторе).
  "warpTLx", "warpTLy", "warpTRx", "warpTRy", "warpBRx", "warpBRy", "warpBLx", "warpBLy",
  // Материал: три канала заменяют инспектор (−1 — «не задано»), свечение
  // прибавляется (см. «Материал» в инспекторе).
  "roughness", "metallic", "ao", "emissive", "ior",
];

/**
 * `text` — строковый параметр текстового объекта: база в скрипте объекта
 * (`text = "привет"`), переопределение — в блоке события. Отдельно от чисел,
 * потому что кадр отдаёт его строкой, а не числом.
 */
export const TEXT_PARAMETER = "text";

/**
 * Имена ядра, которых нет в подсказках, но занимать их всё равно нельзя.
 *
 * Медиа-параметры подсказываются только медиа-объекту (их список не зависит от
 * вида), а синонимы (`rot`, `size_x`, `rate`…) ядро понимает, но показывает
 * один канонический вариант. Локальной переменной такое имя быть не может —
 * иначе признак «локальная переменная» срабатывал бы на `rot = 5`.
 */
export const SCRIPT_HIDDEN_NAMES: readonly string[] = [
  "play", "speed", "volume", "rot", "size_x", "size_y", "skew_x", "skew_y", "rate", "gain",
];

/** Все имена, занятые языком: параметры, каналы, `text` и скрытые синонимы. */
const SCRIPT_NAMES: ReadonlySet<string> = new Set([
  ...SCRIPT_PARAMETERS,
  ...SCRIPT_HIDDEN_NAMES,
  TEXT_PARAMETER,
]);

/** Занято ли имя языком (тогда слева это параметр, а не локальная переменная). */
export function isScriptName(name: string): boolean {
  return SCRIPT_NAMES.has(name);
}
