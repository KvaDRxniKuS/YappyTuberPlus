/**
 * Сквозной номер кадра для окон и оверлея.
 *
 * Движок пересоздаётся (смена структуры, «Стоп», сброс таймлайна), и его
 * собственная нумерация начинается заново. Оверлей же отбрасывает кадры с
 * номером не больше прошлого — так он склеивает дубли, приходящие сразу по
 * двум дорогам. После пересоздания все новые кадры выглядели «старыми», и
 * источник в OBS замирал до перезапуска.
 *
 * Поэтому номер выдаёт редактор: он живёт всё время работы окна.
 */

let last = 0;

/** Следующий номер кадра. Только растёт — и через пересоздание движка тоже. */
export function nextFrameSeq(): number {
  last += 1;
  return last;
}

/** Последний выданный номер: по нему видно, что счётчик не откатился. */
export function currentFrameSeq(): number {
  return last;
}
